'use strict';
const { contextBridge, ipcRenderer } = require('electron');
const on = (ch, cb) => ipcRenderer.on(ch, (e, v) => cb(v));
contextBridge.exposeInMainWorld('api', {
  onOpen: (cb) => on('open', cb),
  onChunk: (cb) => on('chunk', cb),
  onDone: (cb) => on('done', cb),
  onError: (cb) => on('error', cb),
  run: (action, instruction) => ipcRenderer.send('run', { action, instruction }),
  cancel: () => ipcRenderer.send('cancel'),
  close: () => ipcRenderer.send('close'),
  copy: (t) => ipcRenderer.send('copy', t),
  replace: (t) => ipcRenderer.send('replace', t),
  setKey: (k) => ipcRenderer.invoke('setKey', k),
  openConsole: () => ipcRenderer.send('openConsole'),
  getData: () => ipcRenderer.invoke('getData'),
  saveContacts: (list) => ipcRenderer.invoke('saveContacts', list),
  saveActions: (list) => ipcRenderer.invoke('saveActions', list),
  setLang: (l) => ipcRenderer.send('setLang', l),
  saveNote: (t) => ipcRenderer.invoke('saveNote', t),
  saveTone: (n, t) => ipcRenderer.invoke('saveTone', n, t),
  onMoved: (cb) => on('moved', cb),
  onClosing: (cb) => on('closing', cb),
  studyList: () => ipcRenderer.invoke('study:list'),
  studyGet: (id) => ipcRenderer.invoke('study:get', id),
  studyCreate: (a, raw) => ipcRenderer.invoke('study:create', a, raw),
  studyReview: (id, item, g) => ipcRenderer.invoke('study:review', id, item, g),
  studySession: (id, r, t) => ipcRenderer.invoke('study:session', id, r, t),
  studyDelete: (id) => ipcRenderer.invoke('study:delete', id),
  settingsGet: () => ipcRenderer.invoke('settings:get'),
  settingsSet: (k, v) => ipcRenderer.invoke('settings:set', k, v),
  setHotkey: (a, kind) => ipcRenderer.invoke('settings:hotkey', a, kind),
  studyOverview: () => ipcRenderer.invoke('study:overview'),
  homeData: () => ipcRenderer.invoke('homeData'),
  onHome: (cb) => on('home', cb),
  chatList: () => ipcRenderer.invoke('chat:list'), chatGet: (id) => ipcRenderer.invoke('chat:get', id), chatSend: (p) => ipcRenderer.invoke('chat:send', p),
  chatDelete: (id) => ipcRenderer.invoke('chat:delete', id), chatRename: (id, t) => ipcRenderer.invoke('chat:rename', id, t), chatStop: () => ipcRenderer.send('chat:stop'),
  onChat: (cb) => on('chat:ev', cb), onChatPrefill: (cb) => on('chat:prefill', cb),
  updateGet: () => ipcRenderer.invoke('update:get'), updateCheck: () => ipcRenderer.invoke('update:check'), updateInstall: () => ipcRenderer.invoke('update:install'),
  updateSkip: () => ipcRenderer.invoke('update:skip'), updatePage: () => ipcRenderer.send('update:page'), onUpdate: (cb) => on('update:ev', cb),
  permsStatus: () => ipcRenderer.invoke('perms:status'), permsTest: (k) => ipcRenderer.invoke('perms:test', k), permsRequest: (k) => ipcRenderer.invoke('perms:request', k), permsOpen: (k) => ipcRenderer.send('perms:open', k),
  actionsBuiltin: () => ipcRenderer.invoke('actions:builtin'), actionsTest: (p) => ipcRenderer.invoke('actions:test', p), actionsStop: () => ipcRenderer.send('actions:stop'),
  actionsExport: () => ipcRenderer.invoke('actions:export'), actionsImport: () => ipcRenderer.invoke('actions:import'), onActions: (cb) => on('actions:ev', cb),
  barAsk: (t) => ipcRenderer.invoke('bar:ask', t), barExec: (t) => ipcRenderer.invoke('bar:exec', t), barClose: () => ipcRenderer.send('bar:close'), barResize: (h) => ipcRenderer.send('bar:resize', h),
  barCopy: (t) => ipcRenderer.send('bar:copy', t), onBarOpen: (cb) => on('bar:open', cb), onBarEv: (cb) => on('bar:ev', cb), onBarClosing: (cb) => on('bar:closing', cb),
  bubbleTranslate: (p) => ipcRenderer.send('bubble:translate', p), bubbleClose: () => ipcRenderer.send('bubble:close'), bubbleCopy: (t) => ipcRenderer.send('bubble:copy', t), bubbleReplace: (t) => ipcRenderer.send('bubble:replace', t),
  onBubbleOpen: (cb) => on('bubble:open', cb), onBubbleEv: (cb) => on('bubble:ev', cb), onBubbleClosing: (cb) => on('bubble:closing', cb),
  search: (t) => ipcRenderer.send('search', t),
  addCalendar: (t) => ipcRenderer.invoke('addCalendar', t),
  sendTo: (contactId, channel, text) => ipcRenderer.invoke('sendTo', { contactId, channel, text }),
});

/* diagnostyka: nieobsłużone błędy z kontekstu preload trafiają do konsoli okna (widać je w teście dymnym) */
window.addEventListener('unhandledrejection', (e) => { console.error('PRELOAD-REJECTION ' + (e.reason && (e.reason.stack || e.reason.message || e.reason))); });
window.addEventListener('error', (e) => { console.error('PRELOAD-ERROR ' + e.message + ' @' + e.filename + ':' + e.lineno); });
